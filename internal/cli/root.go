// Package cli is the Release CLI's command surface: the command tree, its
// flags, and the mapping from an outcome to an exit status, per the Command
// Surface and Output Renderer components of
// specs/containers/release-cli/release-cli-container.md.
//
// It holds no release logic. Every release capability lives in the release
// core module; this package parses, delegates and renders.
//
// `--help` text is cobra's rendering of the declarations, never written by
// hand, and testdata/help/ holds its golden copy (one file per command), which
// the contract makes normative for the surface's shape.
package cli

import (
	"bufio"
	"context"
	"fmt"
	"io"
	"os"

	"github.com/spf13/cobra"
	"golang.org/x/term"

	"github.com/brettcallaghan/release/internal/buildinfo"
	"github.com/brettcallaghan/release/internal/config"
)

// streams carries the two output streams and the status the run decided on.
//
// A cobra RunE can only signal failure with a non-nil error, which cobra
// renders as "Error: …" and which Execute maps to StatusInvalid. A command
// that refuses an expected condition is not an argument error, so it sets
// exitCode and returns nil instead.
//
// cfg and root are the loaded configuration and the repository root, set by
// the Configuration Loader before any subcommand's own work.
type streams struct {
	out      io.Writer
	err      io.Writer
	exitCode Status

	// in is standard input, and interactive whether it is a terminal: the
	// only condition under which a command prompts.
	in          io.Reader
	interactive bool
	// stdin buffers in for the prompts; see reader.
	stdin *bufio.Reader

	cfg  config.Config
	root string
}

// Execute parses args against the command tree, runs the selected command,
// and returns the process exit status. It is the one function main calls,
// and the one the in-process tests call, so both exercise the same mapping.
func Execute(args []string, stdout, stderr io.Writer) int {
	s := &streams{out: stdout, err: stderr, exitCode: StatusSuccess, in: os.Stdin, interactive: isTerminal(os.Stdin)}
	return s.execute(args)
}

// execute runs args against the command tree with s's streams.
func (s *streams) execute(args []string) int {
	stdout, stderr := s.out, s.err
	root := newRootCmd(s)
	root.SetArgs(args)
	root.SetOut(stdout)
	root.SetErr(stderr)
	if err := root.Execute(); err != nil {
		return int(StatusInvalid)
	}
	return int(s.exitCode)
}

// newRootCmd builds the command tree. Subcommands are added here as the
// features that own them land.
//
// The root carries a RunE because cobra's default for a bare invocation is to
// print usage and exit 0, and a bare `release` names no command: invalid
// arguments, exit 2. The usage goes to standard error, which is where the
// contract puts every diagnostic.
//
// The Configuration Loader runs as the root's persistent pre-run, so it
// precedes every subcommand's own work, and a refused configuration ends the
// run with exit 2 before anything else runs. The root itself does no
// repository work and loads nothing.
func newRootCmd(s *streams) *cobra.Command {
	var (
		showVersion bool
		repo        string
		configPath  string
	)

	root := &cobra.Command{
		Use:   "release",
		Short: "Compute versions, author changelogs and stage releases from git history",
		Long: "release computes the next version from git history, assembles and renders\n" +
			"its changelog, and stages the release on a stage branch for review.",
		Args:          cobra.NoArgs,
		SilenceUsage:  true,
		SilenceErrors: false,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if showVersion {
				fmt.Fprintf(s.out, "release %s\n", buildinfo.Version())
				return nil
			}
			cmd.SetOut(s.err)
			if err := cmd.Usage(); err != nil {
				return err
			}
			s.exitCode = StatusInvalid
			return nil
		},
		PersistentPreRunE: func(cmd *cobra.Command, _ []string) error {
			if !cmd.HasParent() || cmd.Name() == "help" {
				return nil
			}
			ctx := cmd.Context()
			if ctx == nil {
				ctx = context.Background()
			}
			cfg, root, err := loadConfig(ctx, repo, configPath)
			if err != nil {
				return err
			}
			s.cfg, s.root = cfg, root
			return nil
		},
	}
	// cobra's autogenerated `completion` command is not part of the
	// contract's command surface.
	root.CompletionOptions.DisableDefaultCmd = true

	// -V, not cobra's built-in -v: the contract reserves -v for --verbose.
	root.Flags().BoolVarP(&showVersion, "version", "V", false, "Print the tool's own version")

	root.PersistentFlags().StringVarP(&repo, "repo", "C", "", "Operate on the repository at this `path` instead of the working directory")
	root.PersistentFlags().StringVar(&configPath, "config", "", "Use this configuration `file` instead of discovering one")

	root.AddCommand(newVersionCmd(s))
	root.AddCommand(newChangelogCmd(s))
	root.AddCommand(newConfigCmd(s))
	root.AddCommand(newCutCmd(s))

	return root
}

// isTerminal reports whether f is a terminal. A character device is not
// enough: the null device is one.
func isTerminal(f *os.File) bool {
	return term.IsTerminal(int(f.Fd()))
}
