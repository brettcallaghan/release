#!/usr/bin/env bash
#
# Regenerate every artifact derived from schemas/*.strata.
#
# The .strata files are the single source of truth. Everything this
# script writes is generated and must not be hand-edited — each output
# carries a generated-by banner saying so.
#
# Usage:
#   scripts/generate-schemas.sh          # regenerate in place
#   scripts/generate-schemas.sh --check  # fail if any output is stale
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

SRC="schemas"
SCHEMA_OUT="internal/schema"
GO_OUT="internal/releasemodel"

if ! command -v strata >/dev/null 2>&1; then
  echo "error: strata not found on PATH." >&2
  echo "  Install it with scripts/install-strata-cli.sh (the session-start hook" >&2
  echo "  runs it for you when STRATA_ACCESS_TOKEN is set)." >&2
  exit 1
fi

# The compiler release is pinned in schemas/strata.version, so regeneration
# is reproducible: a new strata release must not change the output of
# unchanged sources. Update the pin deliberately and regenerate.
want="$(tr -d '[:space:]' <"$SRC/strata.version")"
have="$(strata --version 2>/dev/null || true)"
if [[ "$have" != "strata-cli ${want#v}" ]]; then
  echo "error: strata is '$have', but $SRC/strata.version pins $want." >&2
  echo "  Install the pinned release: scripts/install-strata-cli.sh $want" >&2
  exit 1
fi

CHECK=0
[[ "${1:-}" == "--check" ]] && CHECK=1

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# 1. Validate. --target ast runs the parser and every semantic check but
#    emits only JSON, so it is the cheapest correctness gate. Nothing is
#    written to the tree until this passes.
strata build "$SRC" --target ast --output "$WORK/ast" --error-format json

# 2. Bundled JSON Schema covering every type: the changelog corpus and the
#    collector records. The changelog contract names this as the shape
#    artifact for validators.
strata build "$SRC" --target json-schema --output "$WORK/schema"
mv "$WORK/schema/ReleaseModel.schema.json" "$WORK/schema/release-model.schema.json"

# 2.25. The changelog schema rooted at Changelog: the artifact a consumer
#       validates a corpus against before rendering, per the changelog
#       contract. The bundle above has no root, so it accepts any instance.
strata build "$SRC" --target json-schema \
  --config "$SRC/overlays/changelog.json" \
  --output "$WORK/changelog"
mv "$WORK/changelog/ReleaseModel.schema.json" "$WORK/schema/changelog.schema.json"

# 2.5. go:embed cannot reach outside its own package directory, so the
#      wrapper lives beside the JSON. It is written here rather than by hand
#      so the package's contents and its exported var cannot drift apart.
cat >"$WORK/schema/embed.go" <<'GOFILE'
// Code generated by scripts/generate-schemas.sh. DO NOT EDIT.

// Package schema embeds the JSON Schema bundle this package holds, so a
// consumer needs no file access at runtime to read it.
package schema

import _ "embed"

// ReleaseModel is the bundle of every type's definition — the changelog
// corpus and the collector records — with no root, so it validates nothing
// on its own: address a definition by JSON Pointer.
// release-model.schema.json.
//
//go:embed release-model.schema.json
var ReleaseModel []byte

// Changelog is the changelog corpus schema, rooted at Changelog: the one a
// consumer validates an instance against before rendering.
// changelog.schema.json.
//
//go:embed changelog.schema.json
var Changelog []byte
GOFILE

# 3. Go types for the release core. strata does not align struct fields the
#    way gofmt does, and scripts/format-check lists every unformatted file,
#    generated or not.
strata build "$SRC" --target go --output "$WORK/go"
gofmt -w "$WORK/go"

sync_dir() {
  local src="$1" dest="$2"
  if [[ $CHECK -eq 1 ]]; then
    if ! diff -r -q "$src" "$dest" >/dev/null 2>&1; then
      echo "error: $dest is stale — run scripts/generate-schemas.sh" >&2
      diff -r "$src" "$dest" >&2 || true
      return 1
    fi
  else
    rm -rf "$dest"
    mkdir -p "$(dirname "$dest")"
    cp -r "$src" "$dest"
  fi
}

rc=0
sync_dir "$WORK/schema" "$SCHEMA_OUT" || rc=1
sync_dir "$WORK/go" "$GO_OUT" || rc=1

if [[ $rc -ne 0 ]]; then
  exit 1
fi

if [[ $CHECK -eq 1 ]]; then
  echo "generated artifacts are up to date"
else
  echo "regenerated:"
  echo "  $SCHEMA_OUT  (JSON Schema + embed.go)"
  echo "  $GO_OUT  (Go)"
fi
